    override fun decode(data: ByteArray, fileName: String): MusicResult {
        if (data.size < 0x2C) throw IllegalArgumentException("KGM/VPR: file too small")
        val isVpr = startsWith(data, VPR_HEADER)
        val isKgm = startsWith(data, KGM_HEADER)
        if (!isVpr && !isKgm) throw IllegalArgumentException("KGM/VPR: bad magic, expected KGM or VPR header")

        val headerLen = readUInt32LE(data, 0x10)
        if (headerLen < 0x2C || headerLen > data.size) {
            throw IllegalArgumentException("KGM/VPR: invalid header length $headerLen")
        }

        // 17 字节密钥: 0x1C 处 16 字节, 第 17 字节隐式为 0
        val key = ByteArray(17)
        System.arraycopy(data, 0x1C, key, 0, 16)

        val audio = data.copyOfRange(headerLen, data.size)
        for (pos in audio.indices) {
            var med8 = (key[pos % 17].toInt() xor audio[pos].toInt()) and 0xFF
            med8 = med8 xor ((med8 and 0x0F) shl 4)
            var msk8 = getMask(pos)
            msk8 = msk8 xor ((msk8 and 0x0F) shl 4)
            audio[pos] = (med8 xor msk8).toByte()
            if (isVpr) {
                audio[pos] = (audio[pos].toInt() xor KGM_VPR_MASK_DIFF[pos % 17]).toByte()
            }
        }

        return MusicResult(audio, AudioSniffer.sniff(audio, null))
    }

    private fun getMask(pos: Int): Int {
        var offset = pos shr 4
        var value = 0
        while (offset >= 0x11) {
            value = value xor KGM_TABLE_1[offset % 272]
            offset = offset shr 4
            value = value xor KGM_TABLE_2[offset % 272]
            offset = offset shr 4
        }
        return KGM_MASK_V2_PRE_DEF[pos % 272] xor value
    }

    private fun startsWith(data: ByteArray, prefix: IntArray): Boolean {
        if (data.size < prefix.size) return false
        for (i in prefix.indices) {
            if ((data[i].toInt() and 0xFF) != prefix[i]) return false
        }
        return true
    }

    private fun readUInt32LE(b: ByteArray, off: Int): Int =
        (b[off].toInt() and 0xFF) or
            ((b[off + 1].toInt() and 0xFF) shl 8) or
            ((b[off + 2].toInt() and 0xFF) shl 16) or
            ((b[off + 3].toInt() and 0xFF) shl 24)
}
